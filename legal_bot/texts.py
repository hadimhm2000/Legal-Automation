def lavayeh_message(items):
    lines = ["📝 این لوایح در پرونده وجود دارد:"]
    for it in items:
        lines.append(f"• لایحه به شماره {it['number']} مورخ {it['date']} از طرف «{it['sender']}»")
    lines.append("")
    lines.append(f"درصورتی که نیاز به استعلام دارید وارد ربات زیر شوید و استعلام خود را انجام دهید:\n"
                 f"آدرس ربات: {config.LAVAYEH_BOT}")
    return "\n".join(lines)


